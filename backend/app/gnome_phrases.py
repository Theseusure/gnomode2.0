def pick_gnome_phrase(*, avoid: str | None = None) -> str:
    """Pick a random phrase, preferring one different from the last sent."""
    if len(GNOME_TIRED_PHRASES) == 1:
        return GNOME_TIRED_PHRASES[0]
    if avoid and avoid in GNOME_TIRED_PHRASES:
        choices = [p for p in GNOME_TIRED_PHRASES if p != avoid]
        return random.choice(choices)
    return random.choice(GNOME_TIRED_PHRASES)


def phrase_count() -> int:
    return len(GNOME_TIRED_PHRASES)
